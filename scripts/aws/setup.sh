#!/usr/bin/env bash
# Set up (or update) Rhythm AI Trader on a fresh Ubuntu 24.04 EC2 instance.
# Private by design: every port stays on 127.0.0.1; you reach the dashboard through an
# SSH tunnel from your Mac (docs/AWS_SETUP.md). Safe to re-run: it pulls the latest code,
# keeps your existing .env and rebuilds.
#
# Usage (on the server, from the repository folder):  bash scripts/aws/setup.sh
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_DIR"
say() { printf '\n==> %s\n' "$*"; }

if [[ "$(id -u)" -eq 0 ]]; then
  echo "Run this as the normal 'ubuntu' user (it uses sudo where needed)." >&2
  exit 1
fi

say "Swap (2 GB): the image builds need more memory than a small instance has"
if ! swapon --show | grep -q '/swapfile'; then
  sudo fallocate -l 2G /swapfile
  sudo chmod 600 /swapfile
  sudo mkswap /swapfile >/dev/null
  sudo swapon /swapfile
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
fi

say "Docker, Compose, git, automatic security updates"
if ! command -v docker >/dev/null || ! sudo docker compose version >/dev/null 2>&1; then
  sudo apt-get update -y
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y docker.io docker-compose-v2 git \
    unattended-upgrades openssl
  sudo systemctl enable --now docker
fi
sudo usermod -aG docker "$USER" || true

say "Latest code"
if [[ -d .git ]]; then
  git pull --ff-only
fi
git log --oneline -1

say "Settings (.env): created once with random secrets, then kept"
if [[ ! -f .env ]]; then
  umask 077
  rand() { openssl rand -base64 48 | tr -d '/+=\n' | cut -c1-"$1"; }
  cat > .env <<ENV
# Generated by scripts/aws/setup.sh on $(date -u +%Y-%m-%dT%H:%MZ). Never commit or share.
# Private server reached only through an SSH tunnel, so the app runs in "local" mode
# (plain http://127.0.0.1 in your browser). PAPER/RESEARCH only: live trading does not exist.
RHYTHM_ENVIRONMENT=local
RHYTHM_TRADING_MODE=RESEARCH_ONLY
RHYTHM_LOG_LEVEL=INFO
RHYTHM_LOG_JSON=true
RHYTHM_MARKET_DATA_PROVIDER=none
RHYTHM_BROKER_ADAPTER=none
RHYTHM_EVENT_PROVIDER=none
RHYTHM_FUNDAMENTALS_PROVIDER=none
RHYTHM_RESEARCH_PROVIDER=none
RHYTHM_AUTH__ENABLED=true
RHYTHM_AUTH__SECRET_KEY=$(rand 48)
RHYTHM_METRICS__TOKEN=$(rand 40)
POSTGRES_USER=rhythm
POSTGRES_PASSWORD=$(rand 32)
POSTGRES_DB=rhythm
# Read-only Sharekhan link: add the keys with  bash scripts/aws/sharekhan_keys.sh
ENV
  chmod 600 .env
  echo "Created .env (permissions 600)."
else
  echo "Keeping existing .env."
fi

say "Build and start (first run takes 10-20 minutes)"
sudo docker compose --env-file .env up -d --build
sudo docker image prune -f >/dev/null || true

say "Waiting for the API"
for _ in $(seq 1 60); do
  if curl -fsS http://127.0.0.1:8000/health/live >/dev/null 2>&1; then break; fi
  sleep 5
done
curl -sS http://127.0.0.1:8000/health/ready || true
echo

say "This server's outgoing IP (register this with Sharekhan as the static IP)"
curl -4 -fsS https://api.ipify.org || echo "(could not check)"
echo

cat <<'NEXT'

Done. Next (docs/AWS_SETUP.md):
  1. Create your sign-in, once:
       sudo docker compose exec api rhythm-cli user-create --username owner --role owner
  2. On your Mac, open the tunnel and browse http://127.0.0.1:3300
  3. When Sharekhan gives you the keys:  bash scripts/aws/sharekhan_keys.sh
NEXT
